const TIERS = { hook: "server hook", overlay: "overlay" };

/** The per-version result pages dev/compat.sh writes, titled from their own header line. */
function compatPages() {
	const dir = path.join(REPO, "docs", "compat");
	return fs
		.readdirSync(dir)
		.filter((f) => f.endsWith(".md") && f !== "README.md")
		.map((file) => {
			const src = `docs/compat/${file}`;
			const text = fs.readFileSync(path.join(REPO, src), "utf8");
			const m = text.match(
				/GitLab CE ([\d.]+) \(([^)]*)\)(?:, tier: (\w+))?, vela commit (\w+), (\d{4}-\d{2}-\d{2})/,
			);
			if (!m) throw new Error(`${src}: no "GitLab CE <version> (...), tier: ..., vela commit ..., <date>" line`);
			const [, version, env, tier = "", , date] = m;
			const pass = (text.match(/^\| PASS \|/gm) ?? []).length;
			const total = (text.match(/^\| (PASS|FAIL|SKIP)\w* \|/gm) ?? []).length;
			const upgrade = file.match(/^upgrade-([\d.]+)-to-([\d.]+)/);
			const tierName = TIERS[tier] ?? "full suite";
			const on = `Live end-to-end results for vela on GitLab CE ${version} (${env})`;
			const result = `${pass} of ${total} cases pass`;
			return {
				src,
				version,
				slug: `compat/${file.replace(/\.md$/, "").replace(/[^a-z0-9]+/gi, "-").toLowerCase()}`,
				title: upgrade
					? `Upgrade ${upgrade[1]} to ${upgrade[2]}, ${tierName}`
					: `GitLab CE ${version}, ${tierName}`,
				description: upgrade
					? `${on} after an in-place upgrade from ${upgrade[1]}, ${tierName} tier: ${result}. Run on ${date}.`
					: `${on} with the ${tierName} tier: ${result}, run with dev/e2e.sh on ${date}.`,
			};
		})
		// Newest GitLab first, then by title (fresh install before upgrade, hook before overlay).
		.sort((a, b) => b.version.localeCompare(a.version, "en", { numeric: true }) || a.title.localeCompare(b.title));
}

const compat = compatPages();
const all = [...PAGES.filter((p) => p.src), ...compat];
const bySrc = new Map(all.map((p) => [p.src, p]));
const urlOf = (p) => (p.slug ? `/docs/${p.slug}` : "/docs");

/** The site URL or GitHub URL for one relative link in `from` (a repo-relative file). */
function rewrite(target, from) {
	if (/^([a-z][a-z0-9+.-]*:|#|\/\/)/i.test(target)) return target; // absolute or in-page
	const [file, hash = ""] = target.split("#");
	const anchor = hash ? `#${hash}` : "";
	let rel = path.posix.normalize(path.posix.join(path.posix.dirname(from), file));
	rel = rel.replace(/\/$/, "");
	if (rel.startsWith("..")) throw new Error(`${from}: link ${target} leaves the repository`);
	const abs = path.join(REPO, rel);
	// A folder with a README that is a page links to that page (docs/compat/ -> /docs/compat).
	const page = bySrc.get(rel) ?? bySrc.get(`${rel}/README.md`);
	if (page) return `${urlOf(page)}${anchor}`;
	if (!fs.existsSync(abs)) {
		console.warn(`sync-docs: ${from} links to ${target}, which does not exist; linking it on GitHub`);
	} else if (rel.endsWith(".md") && rel.startsWith("docs/")) {
		console.warn(`sync-docs: ${rel} is not a page on the site (add it to PAGES); linking it on GitHub`);
	}
	const kind = fs.existsSync(abs) && fs.statSync(abs).isDirectory() ? "tree" : "blob";
	return `${GITHUB}/${kind}/main/${rel}${anchor}`;
}

/** Rewrites Markdown links outside fenced code blocks. */
function rewriteLinks(text, from) {
	return text
		.split(/(^```[\s\S]*?^```)/m)
		.map((part, i) =>
			i % 2 === 1 ? part : part.replace(/\]\(([^)\s]+)\)/g, (_, t) => `](${rewrite(t, from)})`),
		)
		.join("");
}

/** The README without its badges and sponsor section: the site header carries those. */
function trimReadme(text) {
	return text
		.replace(/^\[!\[.*\n/gm, "")
		.replace(/^Documentation: https:\/\/\S+\n+/m, "") // the link to this site
		.replace(/^## Sponsoring is what keeps this free\n[\s\S]*?^---\n/m, "");
}

function frontmatter(p) {
	return `---\ntitle: ${JSON.stringify(p.title)}\ndescription: ${JSON.stringify(p.description)}\nrepoPath: ${JSON.stringify(p.src)}\n---\n\n`;
}

function write(p) {
	let text = fs.readFileSync(path.join(REPO, p.src), "utf8");
	if (p.src === "README.md") text = trimReadme(text);
	text = text.replace(/^# .*\n+/, ""); // the first H1; the page title is the H1
	text = rewriteLinks(text, p.src);
	const file = p.folder ? path.join(OUT, p.slug, "index.md") : path.join(OUT, `${p.slug || "index"}.md`);
	fs.mkdirSync(path.dirname(file), { recursive: true });
	fs.writeFileSync(file, frontmatter(p) + text);
}

fs.rmSync(OUT, { recursive: true, force: true });
for (const p of all) write(p);

// Sidebar order. Fumadocs reads "---Name---" as a section heading.
const rootPages = PAGES.map((p) => (p.separator ? `---${p.separator}---` : p.slug || "index"));
fs.writeFileSync(path.join(OUT, "meta.json"), `${JSON.stringify({ pages: rootPages }, null, "\t")}\n`);
fs.writeFileSync(
	path.join(OUT, "compat", "meta.json"),
	`${JSON.stringify({ title: "Compatibility results", pages: ["index", ...compat.map((p) => p.slug.replace(/^compat\//, ""))] }, null, "\t")}\n`,
);

// Docs not on the site at all, so a new file is noticed rather than silently missing.
for (const f of fs.readdirSync(path.join(REPO, "docs"))) {
	if (f.endsWith(".md") && !bySrc.has(`docs/${f}`)) console.warn(`sync-docs: docs/${f} is not a page on the site (add it to PAGES)`);
}
console.log(`sync-docs: ${all.length} pages written to ${path.relative(SITE, OUT)}`);
