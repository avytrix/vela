/*
 * Builds content/docs from the repository's own Markdown, so the site never holds a second copy
 * that could drift. README.md and docs/*.md stay the source of truth; this script only:
 *
 * - adds frontmatter (title and description, from PAGES below),
 * - drops the first H1 (the page renders its title as the H1),
 * - drops the README's badges and sponsor section (the site has its own Sponsor link),
 * - rewrites relative links: a Markdown file that is a page becomes its site URL, anything else
 *   in the repository (lib/..., dev/up.sh, SECURITY.md) becomes a GitHub URL on main.
 *
 * Result files under docs/compat/ are generated by dev/compat.sh, so they are picked up by name
 * and titled from their own first lines. A docs/*.md that is not listed in PAGES is reported and
 * linked on GitHub instead of failing the build.
 *
 * Usage: node scripts/sync-docs.mjs   (run by postinstall, dev and build)
 */
